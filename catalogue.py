# Fast lookup by ID
PRODUCT_BY_ID: Dict[str, Dict[str, Any]] = {p["id"]: p for p in PRODUCT_CATALOGUE}


def get_products_by_subcategory(subcat: str) -> List[Dict[str, Any]]:
    """Returns all products in a given subcategory before scenario filtering."""
    return [p for p in PRODUCT_CATALOGUE if p.get("subcategory") == subcat]


def get_valid_products(scenario_id: str, subcat: str, guided_subcategories_map: Dict[str, List[str]]) -> List[Dict[str, Any]]:
    """
    Returns every valid catalogue product satisfying:
    1. The scenario is valid and known.
    2. The selected subcategory is enabled for that scenario.
    3. The product's subcategory matches the selected subcategory.
    4. The product is explicitly eligible for the scenario.
    5. Required fields are present and valid (id, name, weight, positive price).
    """
    if not scenario_id:
        return []

    enabled_subcats = guided_subcategories_map.get(scenario_id, [])
    if subcat not in enabled_subcats:
        return []

    valid = []
    for p in PRODUCT_CATALOGUE:
        if p.get("group") == "Discovery":
            continue
        if p.get("subcategory") != subcat:
            continue
        if scenario_id not in p.get("scenarios", []):
            continue
        pid = p.get("id")
        name = p.get("name")
        weight = p.get("weight")
        price = p.get("price")
        if (
            pid and isinstance(pid, str)
            and name and isinstance(name, str)
            and weight and isinstance(weight, str)
            and isinstance(price, (int, float)) and price > 0
        ):
            valid.append(p)
    return valid
